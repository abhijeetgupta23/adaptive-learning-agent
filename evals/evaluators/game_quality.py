from __future__ import annotations

import re
from typing import Any

from pydantic import BaseModel, Field, ValidationError

from backend.agents._parsing import extract_text, parse_json_payload
from backend.agents.teaching.game import GameSpec
from backend.orchestration.cache import cached_system
from backend.orchestration.ptc import AnthropicLike
from backend.schemas.curriculum import LearningUnit

DEFAULT_JUDGE_MODEL = "claude-sonnet-4-6"

# Interactive HTML elements / JS event handlers we expect in a playable game.
_INTERACTIVE_PATTERNS = [
    r"<button\b",
    r"<input\b",
    r"<select\b",
    r"<textarea\b",
    r'\bonclick\s*=',
    r"addEventListener\s*\(",
]

_FORBIDDEN_PATTERNS = [
    r'<script\b[^>]*\bsrc\s*=',      # external script
    r'<link\b[^>]*\bhref\s*=',       # external stylesheet
    r"\bfetch\s*\(",                  # network call
    r"XMLHttpRequest",                # network call
]


GAME_QUALITY_JUDGE_PROMPT = """\
You are evaluating a micro-game generated by a Game Teaching Agent. You will see \
the learning unit's objective, the game's description and instructions, and the \
game's HTML source.

Score each axis 0.0 to 1.0:

- solvable: Can a motivated player reach a clear win state with the provided \
controls and rules? Inspect the HTML logic — if the win condition is unreachable, \
or a required control is missing, score low.
- on_concept: Does the game *mechanic itself* teach the unit's objective? \
A game that displays text about the concept but has unrelated gameplay is \
off-concept. A game that forces the player to reason about the concept through \
the mechanics is on-concept.
- engagement: Is the interaction more engaging than reading a plain text \
explanation of the same concept? Consider: feedback after each action, \
progressive challenge, clear goals.

Overall pass threshold: mean >= 0.7 AND every axis >= 0.5.

Return JSON exactly:

{
  "axis_scores": [
    {"axis": "solvable", "score": <0.0-1.0>, "rationale": "<one sentence>"},
    {"axis": "on_concept", "score": <0.0-1.0>, "rationale": "<one sentence>"},
    {"axis": "engagement", "score": <0.0-1.0>, "rationale": "<one sentence>"}
  ],
  "overall_score": <mean>,
  "passed": <bool>,
  "rationale": "<one-sentence summary>"
}
"""


class GameAxisScore(BaseModel):
    axis: str
    score: float = Field(ge=0.0, le=1.0)
    rationale: str


class GameQualityResult(BaseModel):
    playable: bool
    has_forbidden_resource: bool
    axis_scores: list[GameAxisScore]
    overall_score: float = Field(ge=0.0, le=1.0)
    passed: bool
    rationale: str


class GameQualityEvalError(Exception):
    """Raised when the judge's output cannot be parsed."""


def _has_interactive_elements(html: str) -> bool:
    return any(re.search(p, html, re.IGNORECASE) for p in _INTERACTIVE_PATTERNS)


def _has_forbidden_resource(html: str) -> bool:
    return any(re.search(p, html, re.IGNORECASE) for p in _FORBIDDEN_PATTERNS)


def _build_judge_user_message(game: GameSpec, unit: LearningUnit) -> str:
    return (
        f"Unit objective: {unit.objective}\n\n"
        f"Game title: {game.title}\n"
        f"Game description: {game.description}\n"
        f"Concept: {game.concept}\n"
        f"Player instructions: {game.instructions}\n\n"
        f"Game HTML:\n{game.html}"
    )


async def evaluate_game_quality(
    game: GameSpec,
    unit: LearningUnit,
    *,
    judge: AnthropicLike,
    model: str = DEFAULT_JUDGE_MODEL,
    max_tokens: int = 1024,
) -> GameQualityResult:
    playable = _has_interactive_elements(game.html)
    forbidden = _has_forbidden_resource(game.html)

    response = await judge.messages.create(
        model=model,
        system=cached_system(GAME_QUALITY_JUDGE_PROMPT),
        messages=[{"role": "user", "content": _build_judge_user_message(game, unit)}],
        max_tokens=max_tokens,
    )
    try:
        text = extract_text(response)
        payload: dict[str, Any] = parse_json_payload(text)
    except Exception as exc:
        raise GameQualityEvalError(f"Judge output could not be parsed: {exc}") from exc

    axis_field = payload.get("axis_scores", [])
    try:
        axes = [GameAxisScore.model_validate(a) for a in axis_field]
    except ValidationError as exc:
        raise GameQualityEvalError(f"Axis score validation failed: {exc}") from exc

    llm_overall = payload.get("overall_score")
    llm_passed = payload.get("passed")
    llm_rationale = payload.get("rationale", "")
    if llm_overall is None or llm_passed is None:
        raise GameQualityEvalError(f"Judge output missing required fields: {payload}")

    # Hard gates: must be playable and must not fetch remote resources.
    gated_pass = bool(llm_passed) and playable and not forbidden
    gate_note_parts = []
    if not playable:
        gate_note_parts.append("no interactive elements detected")
    if forbidden:
        gate_note_parts.append("contains forbidden external resource or network call")
    gate_note = "; ".join(gate_note_parts)
    rationale = llm_rationale if not gate_note else f"{llm_rationale} | Gates: {gate_note}"

    return GameQualityResult(
        playable=playable,
        has_forbidden_resource=forbidden,
        axis_scores=axes,
        overall_score=float(llm_overall),
        passed=gated_pass,
        rationale=rationale,
    )
